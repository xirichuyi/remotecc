const { contextBridge, ipcRenderer, webUtils } = require('electron');
const invoke = (channel, ...args) => ipcRenderer.invoke(channel, ...args);
contextBridge.exposeInMainWorld('remoteCC', {
  setEditorDirty: value => invoke('editor:dirty', value),
  discoverHistory: (config, offset) => invoke('history:discover', config, offset),
  loadHistory: (id, older) => invoke('history:load', id, older),
  load: id => invoke('chats:load', id),
  list: () => invoke('chats:list'), create: input => invoke('chats:create', input),
  remove: id => invoke('chats:remove', id), rename: (id, name) => invoke('chats:rename', id, name),
  send: (id, text, attachments) => invoke('chat:send', id, text, attachments),
  organize: (id, patch) => invoke('chats:organize', id, patch),
  cancelQueued: (id, itemId) => invoke('chat:cancel-queued', id, itemId),
  resumeQueue: id => invoke('chat:resume-queue', id),
  stop: id => invoke('chat:stop', id),
  capabilities: (id, refresh) => invoke('chat:capabilities', id, refresh),
  commandInteraction: (id, text) => invoke('chat:interaction', id, text),
  selectEffort: (id, value) => invoke('chat:effort', id, value),
  selectModel: (id, model) => invoke('chat:model', id, model),
  configure: (id, patch) => invoke('chat:configure', id, patch),
  details: (id, section) => invoke('chat:details', id, section),
  fork: id => invoke('chat:fork', id),
  exportChat: id => invoke('chat:export', id),
  respond: (id, requestId, answer) => invoke('chat:respond', id, requestId, answer),
  connect: input => invoke('ssh:connect', input), disconnect: input => invoke('ssh:disconnect', input),
  tunnels: id => invoke('ssh:tunnels', id),
  forward: (id, localPort, remotePort, remove) => invoke('ssh:forward', id, localPort, remotePort, remove),
  connectionState: input => invoke('ssh:state', input),
  listFiles: (id, folder, hidden, force) => invoke('files:list', id, folder, hidden, force),
  listDirectory: (id, folder, hidden, force) => invoke('files:list-dir', id, folder, hidden, force),
  refreshFile: (id, file) => invoke('files:refresh', id, file),
  watchDirectories: (id, directories) => invoke('files:watch', id, directories),
  searchFiles: (id, query) => invoke('files:search', id, query),
  gitStatus: id => invoke('files:git-status', id),
  gitFileDiff: (id, file) => invoke('files:git-diff', id, file),
  createEntry: (id, directory, name, folder) => invoke('files:create', id, directory, name, folder),
  renameEntry: (id, file, name) => invoke('files:rename', id, file, name),
  removeEntry: (id, file, recursive) => invoke('files:remove', id, file, recursive),
  onFilesChanged: callback => ipcRenderer.on('files:changed', (_event, data) => callback(data)),
  saveFile: (id, file, text, revision) => invoke('files:save', id, file, text, revision),
  gitDiff: id => invoke('files:diff', id),
  cancelFiles: kind => invoke('files:cancel', kind),
  preview: (id, file) => invoke('files:preview', id, file),
  attach: (id, file) => invoke('files:attach', id, file),
  uploadDropped: (id, files) => invoke('files:drop', id, files.map(file => webUtils.getPathForFile(file))),
  pasteImage: (id, bytes) => invoke('files:paste-image', id, bytes),
  suggestFiles: (id, query) => invoke('files:suggest', id, query),
  upload: (id, folder) => invoke('files:upload', id, folder),
  download: (id, file) => invoke('files:download', id, file),
  openFile: (id, file) => invoke('files:open', id, file),
  setWorkspace: (id, directory) => invoke('workspace:set', id, directory),
  openLink: url => invoke('link:open', url),
  onChanged: callback => ipcRenderer.on('chat:changed', (_event, data) => callback(data)),
  onRecoveryError: callback => ipcRenderer.on('ssh:recovery-error', (_event, message) => callback(message)),
  onConnection: callback => ipcRenderer.on('ssh:state', (_event, data) => callback(data)),
  onProgress: callback => ipcRenderer.on('files:progress', (_event, data) => callback(data)),
});
